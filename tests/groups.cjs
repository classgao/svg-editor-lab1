const assert=require("node:assert/strict");
const {EditorSession}=require("../dist/application/EditorSession.js");
const {CommandDispatcher}=require("../dist/cli/CommandDispatcher.js");
const {CommandParser}=require("../dist/cli/CommandParser.js");
const s=new EditorSession(),cli=new CommandDispatcher(s),parser=new CommandParser();
const run=line=>cli.dispatch(parser.parse(line));
run("init");
run("create g scene");
run("create g node in scene");
run("create rect r 10 20 100 50 red in node");
run('create text t 20 40 "in" in node');
run("create circle c 5 6 2 in scene");
run("create ellipse e 1 2 3 4 in scene");
run("create line l 0 0 5 5 black in scene");
run('create text literal 0 0 "in"');
assert.ok(run("show r").includes("parent=g#node"));
assert.ok(run("show scene").includes("parent=svg"));
assert.ok(run("tree node").includes('text#t (20,40) "in"'));
const before=run("tree");
run("move scene 10 -5");
assert.ok(run("show r").includes("x=20 y=15"));
assert.ok(run("show t").includes("x=30 y=35"));
run("undo");assert.equal(run("tree"),before);
run("scale scene 2");assert.ok(run("show r").includes("width=200"));
run("undo");assert.equal(run("tree"),before);
for(const bad of ["create rect r 0 0 1 1","create g x in missing","create g x in r"]){
 assert.throws(()=>run(bad));assert.equal(run("tree"),before);
}
run("redo");run("undo");assert.equal(run("tree"),before);
run("delete node");
assert.throws(()=>run("show r"),/no such shape/);
assert.throws(()=>run("show t"),/no such shape/);
run("undo");assert.equal(run("tree"),before);
run("redo");run("undo");assert.equal(run("tree"),before);
run("delete r");run("undo");assert.equal(run("tree"),before);
run("set scene fill blue");
assert.ok(run("show scene").includes("fill=blue"));
assert.ok(run("show r").includes("fill=red"));
run("undo");assert.equal(run("tree"),before);
assert.throws(()=>run("set scene x 5"),/unknown attribute/);
run("create g empty");
assert.throws(()=>run("scale empty 0"),/positive/);
run("create text huge 1e308 0 overflow in node");
const huge=run("tree");
assert.throws(()=>run("move scene 1e308 0"),/finite/);
assert.equal(run("tree"),huge);
assert.throws(()=>run("scale scene 2"),/finite/);
assert.equal(run("tree"),huge);
run("undo");assert.throws(()=>run("show huge"),/no such shape/);
run("redo");assert.equal(run("tree"),huge);
run("delete scene");assert.throws(()=>run("show c"),/no such shape/);
run("undo");assert.equal(run("tree"),huge);
const {Group}=require("../dist/domain/shapes/Group.js");
const a=new Group("a"),b=new Group("b");
a.insertChild(b,0);
assert.throws(()=>b.insertChild(a,0),/cyclic/);
assert.throws(()=>a.insertChild(a,0),/cyclic/);
console.log("Group checks passed: nesting, all shapes, atomic transforms, subtree deletion and history.");
