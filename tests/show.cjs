const assert = require("node:assert/strict");
const { EditorSession } = require("../dist/application/EditorSession.js");
const { CommandDispatcher } = require("../dist/cli/CommandDispatcher.js");
const session = new EditorSession();
const cli = new CommandDispatcher(session);
const run = (...tokens) => cli.dispatch(tokens);
assert.throws(() => run("show", "r1"), /no document/);
run("init");
assert.throws(() => run("show", "missing"), /no such shape: missing/);
assert.throws(() => run("undo"), /undo not allowed/);
run("create", "rect", "r1", "0.1", "-20", "100", "50");
const original = "rect#r1  parent=svg\n  x=0.1 y=-20 width=100 height=50";
assert.equal(run("show", "r1"), original);
assert.throws(() => run("show"), /usage: show/);
assert.throws(() => run("show", "r1", "extra"), /usage: show/);
run("set", "r1", "fill", "rgb(10, 20, 30)");
run("set", "r1", "stroke", "#123456");
run("set", "r1", "stroke-width", "2.5");
assert.equal(run("show", "r1"), original +
  "\n  fill=rgb(10, 20, 30)\n  stroke=#123456\n  stroke-width=2.5");
run("undo");
const withoutWidth = run("show", "r1");
assert.ok(!withoutWidth.includes("stroke-width"));
assert.throws(() => run("show", "missing"), /no such shape/);
run("redo");
assert.ok(run("show", "r1").includes("stroke-width=2.5"));
run("undo");
run("undo");
run("undo");
assert.equal(run("show", "r1"), original);
run("undo");
assert.throws(() => run("show", "r1"), /no such shape/);
run("redo");
assert.equal(run("show", "r1"), original);
run("move", "r1", "10", "20");
assert.ok(run("show", "r1").includes("x=10.1 y=0"));
run("undo");
assert.equal(run("show", "r1"), original);
run("canvas", "400", "300");
assert.equal(run("show", "r1"), original);
assert.throws(() => run("undo"), /undo not allowed/);
assert.throws(() => run("redo"), /undo not allowed/);
assert.ok(run("help").includes("show <id>"));
console.log("Show checks passed: details, missing styles, errors and history preservation.");
