const assert=require("node:assert/strict");
const os=require("node:os"),path=require("node:path"),fs=require("node:fs");
const {EditorSession}=require("../dist/application/EditorSession.js");
const {CommandDispatcher}=require("../dist/cli/CommandDispatcher.js");
const {FileDocumentStore}=require("../dist/infrastructure/FileDocumentStore.js");
const {SvgSerializer}=require("../dist/infrastructure/SvgSerializer.js");
const dir=fs.mkdtempSync(path.join(os.tmpdir(),"svg-save-"));
try {
 const s=new EditorSession(new FileDocumentStore()),cli=new CommandDispatcher(s);
 assert.throws(()=>s.save(),/no document/);
 s.init(400,300);assert.throws(()=>s.save(),/no file path/);
 s.createShape("g","scene",[]);
 s.createShape("rect","r",["1","2","30","40","red"],"scene");
 s.createShape("circle","c",["5","6","2"],"scene");
 s.createShape("ellipse","e",["5","6","2","3"],"scene");
 s.createShape("line","l",["0","0","10","10"],"scene");
 const text='A & <B> "quote" \u4e2d\u6587 \ud83d\ude80\nnext';
 s.createShape("text","t",["20","30",text],"scene");
 const file=path.join(dir,"with spaces.svg");
 assert.ok(cli.dispatch(["save",file]).includes("(6 elements)"));
 const xml=fs.readFileSync(file,"utf8");
 assert.ok(xml.includes('xmlns="http://www.w3.org/2000/svg"'));
 assert.ok(xml.includes('viewBox="0 0 400 300"'));
 assert.ok(xml.includes('A &amp; &lt;B&gt; &quot;quote&quot;'));
 assert.ok(xml.includes("&#10;next</text>"));
 assert.ok(xml.includes('<circle id="c" cx="5" cy="6" r="2"/>'));
 assert.ok(xml.includes('<line id="l" x1="0" y1="0" x2="10" y2="10"/>'));
 assert.throws(()=>s.undo(),/undo not allowed/);
 s.moveShape("r",10,0);s.undo();
 assert.throws(()=>s.save(path.join(dir,"missing","bad.svg")),/cannot write file/);
 s.redo();assert.ok(s.showShape("r").includes("x=11"));
 assert.throws(()=>cli.dispatch(["save",file,"extra"]),/usage/);
 s.save();assert.ok(fs.readFileSync(file,"utf8").includes('x="11"'));
 s.setShapeAttribute("t","text","bad\u0000");
 const before=fs.readFileSync(file,"utf8");
 assert.throws(()=>s.save(),/cannot write file/);
 assert.equal(fs.readFileSync(file,"utf8"),before);
 s.undo();assert.ok(s.showShape("t").includes("A & <B>"));
 s.save();
 assert.deepEqual(fs.readdirSync(dir),["with spaces.svg"]);
 s.reorderShape("r",true);s.save();
 const reordered=fs.readFileSync(file,"utf8");
 assert.ok(reordered.indexOf('id="r"')>reordered.indexOf('id="t"'));
 const attrs=s.getDocument().getShape("r").getAttributes();attrs.x="999";
 assert.ok(s.showShape("r").includes("x=11"));
 s.init();assert.throws(()=>s.save(),/no file path/);
 const empty=new SvgSerializer().serialize(s.getDocument());
 assert.ok(empty.includes('width="800" height="600"'));
 console.log("Save checks passed: six types, escaping, paths, atomic failures, z-order and history.");
} finally {
 fs.rmSync(dir,{recursive:true,force:true});
}
